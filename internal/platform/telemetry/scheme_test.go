// eventsSchemeFile is the scheme to register with the FUS metadata, regenerated with -update.
const eventsSchemeFile = "fus/events-scheme.json"

var update = flag.Bool("update", false, "regenerate "+eventsSchemeFile)

func TestEventsScheme(t *testing.T) {
	scheme, err := eventsScheme()
	require.NoError(t, err)
	var generated bytes.Buffer
	require.NoError(t, fus.WriteEventsSchemeJSON(scheme, &generated))

	if *update {
		require.NoError(t, os.WriteFile(eventsSchemeFile, generated.Bytes(), 0o644))
	}
	committed, err := os.ReadFile(eventsSchemeFile)
	require.NoError(t, err)
	assert.Equal(t, string(committed), generated.String(),
		"the scheme changed: regenerate %s with go test -run TestEventsScheme -update, and register it", eventsSchemeFile)
}

func TestFieldLimit(t *testing.T) {
	for _, group := range definition.Groups {
		for _, event := range group.Events {
			// the sender drops an event with more fields
			assert.LessOrEqual(t, len(event.Fields), fus.MaxDataFields, "%s/%s", group.ID, event.ID)
		}
	}
}

func TestOnlyGlobalRuleRefs(t *testing.T) {
	ref := regexp.MustCompile(`^(enum|regexp)#(.+)$`)
	global := map[string]bool{
		"enum#" + enumBoolean:     true,
		"regexp#" + regexpInteger: true, "regexp#" + regexpVersion: true,
	}
	forEachField(func(group string, event fus.EventDefinition, field fus.FieldDefinition) {
		for _, rule := range field.Rules {
			if ref.MatchString(rule) {
				assert.True(t, global[rule], "%s/%s/%s refers to %s, which is not a global rule", group, event.ID, field.Path, rule)
			}
		}
	})
}

func TestNoNestedRuleSyntax(t *testing.T) {
	forEachField(func(group string, event fus.EventDefinition, field fus.FieldDefinition) {
		for _, rule := range field.Rules {
			if pattern, ok := strings.CutPrefix(rule, "regexp:"); ok {
				// the metadata reads them as rule syntax: alternatives are separate rules
				assert.False(t, strings.ContainsAny(pattern, "{}|"), "%s/%s/%s: %s", group, event.ID, field.Path, rule)
			}
		}
	})
}

func TestFieldsAreDescribed(t *testing.T) {
	forEachField(func(group string, event fus.EventDefinition, field fus.FieldDefinition) {
		assert.NotEmpty(t, field.Description, "%s/%s/%s", group, event.ID, field.Path)
	})
}

func forEachField(check func(group string, event fus.EventDefinition, field fus.FieldDefinition)) {
	for _, group := range definition.Groups {
		for _, event := range group.Events {
			for _, field := range event.Fields {
				check(group.ID, event, field)
			}
		}
	}
}

